export const CATALOG = RAW.trim().split('\n').map(l => {
  const [coins, th, en] = l.split('|');
  return { coins: Number(coins), th: th.trim(), en: (en || '').trim() };
});

const norm = s => String(s ?? '').trim().toLowerCase().replace(/\s+/g, ' ');
const byTh = new Map(CATALOG.map(g => [norm(g.th), g]));
const priceCount = new Map();
for (const g of CATALOG) priceCount.set(g.coins, (priceCount.get(g.coins) || 0) + 1);

export class GiftMatcher {
  constructor(learned = {}) { this.learned = Object.assign(Object.create(null), learned && typeof learned === 'object' ? learned : {}); } // english name (lowercase) -> thai name

  // Remember the Thai name of an English gift name when its price points to exactly one gift.
  learn(enName, coins) {
    const key = norm(enName);
    if (!key || this.learned[key] || CATALOG.some(g => norm(g.en) === key || norm(g.th) === key)) return null;
    const same = CATALOG.filter(g => g.coins === coins);
    if (same.length === 1) { this.learned[key] = same[0].th; return same[0].th; }
    return null;
  }

  // Catalog entry for a live gift (by English name, Thai name, learned alias, or unique price).
  find(gift) {
    const name = norm(gift.name);
    let g = CATALOG.find(c => norm(c.en) === name || norm(c.th) === name);
    if (!g && this.learned[name]) g = byTh.get(norm(this.learned[name]));
    if (!g && priceCount.get(Number(gift.diamonds)) === 1) g = CATALOG.find(c => c.coins === Number(gift.diamonds));
    return g || null;
  }

  thaiName(enName) {
    const key = norm(enName);
    const g = CATALOG.find(g => norm(g.en) === key);
    return g?.th || this.learned[key] || '';
  }

  // Does one rule entry (Thai or English name, or gift id) refer to this live gift?
  matches(entry, gift) {
    const e = norm(entry);
    if (!e) return false;
    if (e === '*') return true;
    const name = norm(gift.name);
    if (e === name || e === norm(gift.id)) return true;
    const g = byTh.get(e);
    if (g) {
      if (g.en && norm(g.en) === name) return true;
      if (this.learned[name] && norm(this.learned[name]) === e) return true;
      if (priceCount.get(g.coins) === 1 && Number(gift.diamonds) === g.coins) return true;
    }
    return false;
  }
}

